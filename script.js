function renderSection(sectionName) {
  const target = document.querySelector(`[data-copy="${sectionName}"]`);
  const section = copy[language][sectionName];
  if (!target || !section) return;
  const title = document.createElement("h1");
  const intro = section.intro ? document.createElement("p") : null;
  const list = document.createElement("ul");

  title.className = "section-title";
  title.textContent = section.title;
  list.className = "section-list";

  if (intro) {
    intro.className = "section-intro";
    intro.textContent = section.intro;
  }

  section.items.forEach((item, index) => {
    const row = document.createElement("li");
    row.dataset.level = item.level;
    row.style.setProperty("--item-index", index);

    const itemRoute = itemRoutes[sectionName]?.[index];
    if (item.description) {
      const button = document.createElement("button");
      const description = document.createElement("p");
      row.classList.add("section-accordion__item");
      if (index === 0) row.classList.add("is-open");
      button.className = "section-accordion__button";
      button.type = "button";
      button.textContent = item.label;
      button.setAttribute("aria-expanded", String(index === 0));
      description.className = "section-accordion__description";
      description.textContent = item.description;
      button.addEventListener("click", () => {
        const willOpen = !row.classList.contains("is-open");
        list.querySelectorAll(".section-accordion__item").forEach(itemRow => {
          itemRow.classList.remove("is-open");
          itemRow.querySelector("button")?.setAttribute("aria-expanded", "false");
        });
        if (willOpen) {
          row.classList.add("is-open");
          button.setAttribute("aria-expanded", "true");
        }
      });
      row.append(button, description);
      list.classList.add("section-list--accordion");
    } else if (itemRoute) {
      const link = document.createElement("a");
      link.textContent = item.label;
      link.href = itemRoute;
      row.append(link);
    } else if (item.value) {
      const label = document.createElement("span");
      const value = document.createElement("a");
      label.className = "contact-label";
      label.textContent = item.label;
      value.className = "contact-value";
      value.textContent = item.value;
      value.href = item.href;
      value.dir = "ltr";
      if (item.href.startsWith("http")) {
        value.target = "_blank";
        value.rel = "noreferrer";
      }
      row.append(label, value);
    } else {
      row.textContent = item.label;
    }

    list.append(row);
  });

  const isCatalogSection = ["architecture", "supply", "services", "custom-machines"].includes(sectionName);
  const content = isCatalogSection ? [title, list, intro] : [title, intro, list];
  target.replaceChildren(...content.filter(Boolean));
}

function renderLanguage() {
  document.documentElement.lang = language;
  site.dataset.lang = language;

  navigationButtons.forEach((button) => {
    button.textContent = copy[language].navigation[button.dataset.target];
  });

  scenes.forEach((scene) => renderSection(scene.dataset.scene));
  languageButton.textContent = language === "en" ? "FA" : "EN";
}

async function loadSceneImage(scene) {
  const image = scene.querySelector("[data-image-source]");
  if (!image || image.dataset.imageState) return;

  image.dataset.imageState = "loading";

  try {
    const response = await fetch(image.dataset.imageSource);
    if (!response.ok) throw new Error("Image source unavailable");
    image.src = (await response.text()).trim();
    image.dataset.imageState = "ready";
  } catch {
    delete image.dataset.imageState;
  }
}

function showCurrentScene() {
  scenes.forEach((scene) => {
    const active = scene.dataset.scene === activeScene;
    scene.classList.toggle("is-active", active);
    scene.setAttribute("aria-hidden", String(!active));
    if (active) loadSceneImage(scene);
  });

  navigationButtons.forEach((button) => {
    button.classList.toggle("is-active", button.dataset.target === activeScene);
  });
}

function navigateToScene(sceneName) {
  if (!availableScenes.has(sceneName) || navigationLocked || sceneName === activeScene) return;
  navigationLocked = true;
  const currentIndex = sceneOrder.indexOf(activeScene);
  const nextIndex = sceneOrder.indexOf(sceneName);
  site.dataset.motion = nextIndex >= currentIndex ? "forward" : "backward";
  window.location.assign(routeByScene[sceneName]);
}

function stepScene(direction) {
  const currentIndex = sceneOrder.indexOf(activeScene);
  const nextIndex = Math.max(0, Math.min(sceneOrder.length - 1, currentIndex + direction));
  if (nextIndex !== currentIndex) {
    window.clearTimeout(parallaxResetTimer);
    site.style.setProperty("--parallax-y", `${direction * -8}px`);
    navigateToScene(sceneOrder[nextIndex]);
  }
}

document.addEventListener("click", (event) => {
  const navigationButton = event.target.closest("[data-target]");
  if (navigationButton) {
    navigateToScene(navigationButton.dataset.target);
    return;
  }

  if (event.target.closest("button[data-language]")) {
    language = language === "en" ? "fa" : "en";
    try {
      window.localStorage.setItem("nazarifar-language", language);
    } catch {}
    renderLanguage();
  }
});

window.addEventListener("hashchange", () => {
  const requested = location.hash.slice(1) || "holding";
  if (availableScenes.has(requested)) navigateToScene(requested);
});

document.addEventListener("keydown", (event) => {
  if (event.repeat) return;
  if (event.key === "ArrowRight" || event.key === "ArrowDown" || event.key === "PageDown") {
    event.preventDefault();
    stepScene(1);
  }
  if (event.key === "ArrowLeft" || event.key === "ArrowUp" || event.key === "PageUp") {
    event.preventDefault();
    stepScene(-1);
  }
});

window.addEventListener(
  "wheel",
  (event) => {
    if (Math.abs(event.deltaY) < 20 || scrollLocked) return;
    event.preventDefault();
    stepScene(event.deltaY > 0 ? 1 : -1);
    scrollLocked = true;
    window.setTimeout(() => {
      scrollLocked = false;
    }, 1050);
  },
  { passive: false },
);

window.addEventListener(
  "touchstart",
  (event) => {
    touchStartY = event.changedTouches[0].clientY;
  },
  { passive: true },
);

window.addEventListener(
  "touchend",
  (event) => {
    const distance = touchStartY - event.changedTouches[0].clientY;
    if (Math.abs(distance) >= 45) {
      stepScene(distance > 0 ? 1 : -1);
    }
  },
  { passive: true },
);

if (window.matchMedia("(hover: hover) and (pointer: fine)").matches) {
  window.addEventListener(
    "pointermove",
    (event) => {
      if (parallaxFrame) return;
      parallaxFrame = window.requestAnimationFrame(() => {
        const centeredY = event.clientY / window.innerHeight - 0.5;
        site.style.setProperty("--parallax-y", `${centeredY * -5}px`);
        parallaxFrame = 0;
      });
    },
    { passive: true },
  );
}

const legacyHash = location.hash.slice(1);
if (activeScene === "holding" && legacyHash && availableScenes.has(legacyHash)) {
  window.location.replace(routeByScene[legacyHash]);
} else {
  renderLanguage();
  showCurrentScene();
}

