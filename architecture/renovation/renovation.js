const languageButton = document.querySelector("[data-language]");
const translatable = [...document.querySelectorAll("[data-i18n]")];
let language = "en";

try {
  const saved = window.localStorage.getItem("nazarifar-language");
  if (saved === "fa" || saved === "en") language = saved;
} catch {
  language = "en";
}

function applyLanguage() {
  document.documentElement.lang = language;
  document.documentElement.dir = language === "fa" ? "rtl" : "ltr";
  document.body.dataset.lang = language;
  document.title = language === "fa" ? "بازسازی — گروه نظری‌فر" : "Renovation — Nazarifar Group";

  document.title = language === "fa"
    ? "دکوراسیون، بازسازی و تجهیز — گروه نظری‌فر"
    : "Decoration, Renovation & Fit-Out — Nazarifar Group";

  translatable.forEach((element) => {
    const key = element.dataset.i18n;
    if (content[language][key]) element.textContent = content[language][key];
  });

  languageButton.textContent = language === "en" ? "FA" : "EN";
}

languageButton.addEventListener("click", () => {
  language = language === "en" ? "fa" : "en";
  try {
    window.localStorage.setItem("nazarifar-language", language);
  } catch {
    // The page remains bilingual even when storage is unavailable.
  }
  applyLanguage();
});

const observer = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      }
    });
  },
  { threshold: 0.14 },
);

document.querySelectorAll(".reveal").forEach((element) => observer.observe(element));

const filterButtons = [...document.querySelectorAll("[data-filter]")];
const projectLists = [...document.querySelectorAll("[data-project-list]")];

filterButtons.forEach((button) => {
  button.addEventListener("click", () => {
    const selected = button.dataset.filter;

    filterButtons.forEach((item) => {
      const active = item === button;
      item.classList.toggle("is-active", active);
      item.setAttribute("aria-pressed", String(active));
    });

    projectLists.forEach((list) => {
      list.hidden = list.dataset.projectList !== selected;
    });
  });
});

applyLanguage();
